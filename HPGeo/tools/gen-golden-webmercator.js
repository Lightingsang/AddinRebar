// Golden for HPGeo.Core/Imagery/WebMercator: EPSG:3857 metres from proj4 (independent implementation) and XYZ
// tile / global-pixel numbers from the textbook formulas, for the 13 sample points of the oracle and a few
// far-flung positions. Also the per-zoom resolution at each sample latitude.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import proj4 from 'proj4';

const here = dirname(fileURLToPath(import.meta.url));
const forwardPath = join(here, '..', 'HPGeo.Tests', 'Fixtures', 'golden-vn2000-to-wgs84.json');
const outPath = join(here, '..', 'HPGeo.Tests', 'Fixtures', 'golden-webmercator.json');

const forward = JSON.parse(readFileSync(forwardPath, 'utf8'));
const samples = forward.cases.filter(c => c.id.startsWith('sample-')).slice(0, 13).map(c => ({ id: c.id, lat: c.lat, lon: c.lon }));
samples.push({ id: 'hanoi', lat: 21.0285, lon: 105.8542 }, { id: 'camau', lat: 8.6, lon: 104.9 }, { id: 'equator-gm', lat: 0, lon: 0 }, { id: 'north', lat: 60, lon: -120 });

const R = 6378137;
function tile(lat, lon, z) {
  const n = 2 ** z;
  const latRad = (lat * Math.PI) / 180;
  const x = ((lon + 180) / 360) * n;
  const y = ((1 - Math.log(Math.tan(latRad) + 1 / Math.cos(latRad)) / Math.PI) / 2) * n;
  return { x, y };
}

const cases = samples.map(s => {
  const [mx, my] = proj4('EPSG:4326', 'EPSG:3857', [s.lon, s.lat]);
  const perZoom = [15, 17, 19].map(z => {
    const t = tile(s.lat, s.lon, z);
    return {
      zoom: z,
      tileX: Math.floor(t.x),
      tileY: Math.floor(t.y),
      pixelX: t.x * 256,
      pixelY: t.y * 256,
      resolutionMPerPx: (2 * Math.PI * R) / 256 / 2 ** z * Math.cos((s.lat * Math.PI) / 180),
    };
  });
  return { ...s, mercatorX: mx, mercatorY: my, perZoom };
});

writeFileSync(outPath, JSON.stringify({ note: 'Generated by tools/gen-golden-webmercator.js (proj4 EPSG:3857 + XYZ formulas). Do not edit by hand.', cases }, null, 2) + '\n', 'utf8');
console.log(`${cases.length} cases -> ${outPath}`);
