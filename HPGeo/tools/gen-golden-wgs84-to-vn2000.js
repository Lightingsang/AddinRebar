// The oracle only converts VN-2000 -> WGS84. The reverse direction is new code, so its golden
// comes from an independent implementation: proj4 (npm) with the same TM-3 definition.
//
// Sign convention, measured 2026-09-18 against the forward golden: PROJ's +towgs84 is the
// *position vector* convention while the oracle applies the EPSG parameters in the *coordinate
// frame* convention (as EPSG method 1032 does). Feeding proj4 the EPSG signs as-is (what the
// sibling tool TraThongTinKinhTuyenTrucVN2000.html does) deviates from the oracle by 0.80 m;
// flipping the three rotation signs brings proj4 to within 0.1 mm of the oracle. The oracle
// wins, so the rotations are flipped here.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import proj4 from 'proj4';

const here = dirname(fileURLToPath(import.meta.url));
const forwardPath = join(here, '..', 'HPGeo.Tests', 'Fixtures', 'golden-vn2000-to-wgs84.json');
const outPath = join(here, '..', 'HPGeo.Tests', 'Fixtures', 'golden-wgs84-to-vn2000.json');

const forward = JSON.parse(readFileSync(forwardPath, 'utf8'));
const h = forward.helmertParameters;
const towgs84 = [h.dx, h.dy, h.dz, -h.rx, -h.ry, -h.rz, h.s].join(',');
const crs = cm =>
  `+proj=tmerc +lat_0=0 +lon_0=${cm} +k=${forward.tm.k0} +x_0=${forward.tm.falseEasting} +y_0=${forward.tm.falseNorthing} ` +
  `+ellps=WGS84 +towgs84=${towgs84} +units=m +no_defs`;

let maxForwardDeviationM = 0;
const cases = forward.cases.map(c => {
  // Cross-check proj4's forward against the oracle (mm level expected), then invert the oracle's lat/lon.
  const [pLon, pLat] = proj4(crs(c.cm), 'WGS84', [c.e, c.n]);
  const dev = Math.hypot((pLat - c.lat) * 111320, (pLon - c.lon) * 111320 * Math.cos((c.lat * Math.PI) / 180));
  if (dev > maxForwardDeviationM) maxForwardDeviationM = dev;
  const [e, n] = proj4('WGS84', crs(c.cm), [c.lon, c.lat]);
  return { id: c.id, cm: c.cm, lat: c.lat, lon: c.lon, e, n, roundTripErrorM: Math.hypot(e - c.e, n - c.n) };
});
if (maxForwardDeviationM > 0.005) {
  throw new Error(`proj4 forward deviates ${maxForwardDeviationM} m from the oracle — sign convention broken?`);
}

const out = {
  note:
    'Generated by tools/gen-golden-wgs84-to-vn2000.js with proj4 (position-vector +towgs84, rotations sign-flipped ' +
    'from the EPSG coordinate-frame values so it agrees with the oracle). Do not edit by hand.',
  proj4Definition: crs('<cm>'),
  proj4ForwardMaxDeviationFromOracleM: maxForwardDeviationM,
  tm: forward.tm,
  cases,
};
writeFileSync(outPath, JSON.stringify(out, null, 2) + '\n', 'utf8');
const worstRoundTrip = Math.max(...cases.map(c => c.roundTripErrorM));
console.log(`${cases.length} reverse cases; proj4 forward vs oracle max ${maxForwardDeviationM.toFixed(5)} m; proj4 round trip max ${worstRoundTrip.toExponential(2)} m -> ${outPath}`);
