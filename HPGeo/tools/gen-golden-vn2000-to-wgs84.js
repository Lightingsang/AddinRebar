// Runs the oracle's own VN-2000 -> WGS84 code (TM inverse + 7-parameter Helmert, sliced out of
// the HTML, never re-typed) over a fixed input set and writes the results as the golden fixture
// the C# port must reproduce. Inputs: the 13 sample points the oracle ships in its textarea
// (TP. Hồ Chí Minh, central meridian 105°45') plus an E/N grid across every central meridian.
import { writeFileSync } from 'node:fs';
import { basename, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readOracle, oraclePath, sliceConst, sliceFunction, evaluate } from './oracle-source.js';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, '..', 'HPGeo.Tests', 'Fixtures', 'golden-vn2000-to-wgs84.json');

const src = readOracle();
const oracle = evaluate(
  [
    sliceConst(src, 'VN2000_HELMERT'),
    sliceFunction(src, 'geodeticToECEF'),
    sliceFunction(src, 'ecefToGeodetic'),
    sliceFunction(src, 'vn2000GeodeticToWGS84'),
    sliceFunction(src, 'tmInverse'),
    sliceFunction(src, 'isVietnamWGS84'),
  ],
  ['VN2000_HELMERT', 'tmInverse', 'isVietnamWGS84', 'vn2000GeodeticToWGS84'],
);

// The sample points live in the textarea's initial value: "POINT E,N" lines.
const textarea = /<textarea id="inputData"[^>]*>([\s\S]*?)<\/textarea>/.exec(src);
if (!textarea) throw new Error('inputData textarea not found');
const samples = textarea[1]
  .split('\n')
  .map(l => /^POINT\s+([-\d.]+),([-\d.]+)/.exec(l.trim()))
  .filter(Boolean)
  .map(m => [Number(m[1]), Number(m[2])]);
if (samples.length < 10) throw new Error(`expected the oracle's sample block, got ${samples.length} points`);

const { PROVINCE_DATA } = evaluate([sliceConst(src, 'PROVINCE_DATA')], ['PROVINCE_DATA']);
const meridians = [...new Set([...PROVINCE_DATA.current, ...PROVINCE_DATA.legacy].flatMap(p => p.cms))].sort((a, b) => a - b);

const tm = { k0: 0.9999, falseEasting: 500000, falseNorthing: 0 };
const cases = [];
let id = 0;
for (const [e, n] of samples) {
  const [lat, lon] = oracle.tmInverse(e, n, 105.75, tm.k0, tm.falseEasting, tm.falseNorthing);
  cases.push({ id: `sample-${++id}`, cm: 105.75, e, n, lat, lon, insideVietnam: oracle.isVietnamWGS84(lat, lon) });
}
for (const cm of meridians) {
  for (const e of [300000, 500000, 700000]) {
    for (const n of [900000, 1200000, 1800000, 2400000]) {
      const [lat, lon] = oracle.tmInverse(e, n, cm, tm.k0, tm.falseEasting, tm.falseNorthing);
      cases.push({ id: `grid-${cm}-${e}-${n}`, cm, e, n, lat, lon, insideVietnam: oracle.isVietnamWGS84(lat, lon) });
    }
  }
}

// A few geodetic-only cases pin the Helmert step on its own (no TM involved).
const helmert = [
  [10.7769, 106.7009], [21.0285, 105.8542], [16.0544, 108.2022], [8.5, 104.9], [22.9, 103.2],
].map(([lat, lon]) => {
  const [wLat, wLon, h] = oracle.vn2000GeodeticToWGS84(lat, lon, 0);
  return { vn2000Lat: lat, vn2000Lon: lon, wgs84Lat: wLat, wgs84Lon: wLon, wgs84Height: h };
});

const out = {
  source: basename(oraclePath()),
  note: 'Generated by tools/gen-golden-vn2000-to-wgs84.js: the oracle JS evaluated as-is. Do not edit by hand.',
  helmertParameters: oracle.VN2000_HELMERT,
  tm,
  sampleCount: samples.length,
  cases,
  helmertOnly: helmert,
};
writeFileSync(outPath, JSON.stringify(out, null, 2) + '\n', 'utf8');
console.log(`${samples.length} samples + ${cases.length - samples.length} grid cases + ${helmert.length} helmert-only -> ${outPath}`);
