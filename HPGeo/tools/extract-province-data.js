// Extracts PROVINCE_DATA (34 current + 63 legacy provinces, each {name, cms[]}) and
// CURRENT_MERIDIAN_ORIGINS (current province -> central meridian -> former-province label)
// from the oracle HTML into HPGeo.Core/Data/vn2000-provinces.json. The JSON is the only
// province data the C# code ever sees; re-run after the oracle changes.
import { writeFileSync } from 'node:fs';
import { basename, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readOracle, oraclePath, sliceConst, evaluate } from './oracle-source.js';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, '..', 'HPGeo.Core', 'Data', 'vn2000-provinces.json');

const src = readOracle();
const { PROVINCE_DATA, CURRENT_MERIDIAN_ORIGINS } = evaluate(
  [sliceConst(src, 'PROVINCE_DATA'), sliceConst(src, 'CURRENT_MERIDIAN_ORIGINS')],
  ['PROVINCE_DATA', 'CURRENT_MERIDIAN_ORIGINS'],
);

function checkCatalog(list, label) {
  for (const p of list) {
    if (typeof p.name !== 'string' || !p.name.trim()) throw new Error(`${label}: record without name`);
    if (!Array.isArray(p.cms) || p.cms.length === 0) throw new Error(`${label}: ${p.name} has no cms`);
    for (const cm of p.cms) {
      if (!Number.isFinite(cm) || cm < 100 || cm > 112 || Math.abs(cm * 4 - Math.round(cm * 4)) > 1e-9) {
        throw new Error(`${label}: ${p.name} has an implausible central meridian ${cm}`);
      }
    }
  }
}
checkCatalog(PROVINCE_DATA.current, 'current');
checkCatalog(PROVINCE_DATA.legacy, 'legacy');

const currentNames = new Set(PROVINCE_DATA.current.map(p => p.name));
for (const [name, byCm] of Object.entries(CURRENT_MERIDIAN_ORIGINS)) {
  if (!currentNames.has(name)) throw new Error(`origins: ${name} is not a current province`);
  const cms = PROVINCE_DATA.current.find(p => p.name === name).cms.map(String);
  for (const cm of Object.keys(byCm)) {
    if (!cms.includes(cm)) throw new Error(`origins: ${name} lists ${cm} which is not one of its cms`);
  }
}

const meridians = [...new Set([...PROVINCE_DATA.current, ...PROVINCE_DATA.legacy].flatMap(p => p.cms))].sort((a, b) => a - b);

const out = {
  source: basename(oraclePath()),
  note: 'Generated by tools/extract-province-data.js from the reference HTML tool. Do not edit by hand.',
  current: PROVINCE_DATA.current,
  legacy: PROVINCE_DATA.legacy,
  origins: CURRENT_MERIDIAN_ORIGINS,
  centralMeridians: meridians,
};
writeFileSync(outPath, JSON.stringify(out, null, 2) + '\n', 'utf8');
console.log(`current ${out.current.length}, legacy ${out.legacy.length}, origins ${Object.keys(out.origins).length}, meridians ${meridians.length} -> ${outPath}`);
